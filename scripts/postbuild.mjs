// Runs after `vite build`. Writes dist/sw.js with the exact list of built files, prints sizes,
// and fails the build if the app grows past its budget.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { gzipSync } from 'node:zlib';

const dist = join(import.meta.dirname, '..', 'dist');
const walk = (dir) => readdirSync(dir).flatMap((name) => {
  const full = join(dir, name);
  return statSync(full).isDirectory() ? walk(full) : [full];
});

const files = walk(dist).filter((f) => !f.endsWith('sw.js'));
const urls = files.map((f) => '/' + relative(dist, f).split('\\').join('/'));
const hash = createHash('sha256');
for (const f of files) hash.update(readFileSync(f));
const version = hash.digest('hex').slice(0, 10);

const sw = `// Generated by scripts/postbuild.mjs. Do not edit.
const CACHE = 'phoneless-${version}';
const FILES = ${JSON.stringify(['/', ...urls.filter((u) => u !== '/index.html'), '/index.html'])};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // never touch other sites
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      // ignoreVary: without it Chrome refuses cached scripts offline. ignoreSearch: "?x" still finds the file.
      const hit = await cache.match(req, { ignoreVary: true, ignoreSearch: true });
      if (hit) return hit;
      try {
        return await fetch(req);
      } catch {
        // Offline and not cached: every page of this app is index.html (hash routes).
        if (req.mode === 'navigate') return cache.match('/index.html', { ignoreVary: true });
        return Response.error();
      }
    }),
  );
});
`;
writeFileSync(join(dist, 'sw.js'), sw);

const kb = (n) => (n / 1024).toFixed(1) + ' KB';
let total = 0, totalGz = 0;
console.log('\nBuilt files');
for (const f of files) {
  const buf = readFileSync(f);
  const gz = gzipSync(buf).length;
  total += buf.length; totalGz += gz;
  console.log('  ' + ('/' + relative(dist, f)).padEnd(40) + kb(buf.length).padStart(10) + kb(gz).padStart(10) + ' gz');
}
console.log('  ' + 'TOTAL'.padEnd(40) + kb(total).padStart(10) + kb(totalGz).padStart(10) + ' gz');
console.log(`  sw.js cache name: phoneless-${version}, ${urls.length} files\n`);

// Budget: the whole app, gzipped. A borrowed phone on a weak signal must load it fast.
const BUDGET = 40 * 1024;
if (totalGz > BUDGET) {
  console.error(`Size budget exceeded: ${kb(totalGz)} gzipped, budget ${kb(BUDGET)}.`);
  process.exit(1);
}
